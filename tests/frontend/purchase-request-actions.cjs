const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const ctx=vm.createContext({React:{createElement:(type,props,...children)=>({type,props,children})},DCLogic:class{setState(p){Object.assign(this.state,typeof p==='function'?p(this.state):p)}},window:{}});
vm.runInContext(fs.readFileSync('public/app.js','utf8')+';globalThis.App=Component;',ctx);
const app=new ctx.App();
const nodes=n=>!n||typeof n!=='object'?[]:Array.isArray(n)?n.flatMap(nodes):[n,...nodes(n.children)];
const text=n=>n==null?'':typeof n==='string'?n:Array.isArray(n)?n.map(text).join(' '):text(n.children);
const request={id:'PR-1',status:'Pending',requestedBy:'Manager',supplierName:'Supplier',dateRequested:'2026-11-23',lines:[{id:1,productId:1,name:'Paper',category:'Supplies',qty:2,unit:'Ream',unitCost:50}]};
const ordered=app.pendingRequestsFirst([{id:'old',status:'Rejected'},{id:'new',status:'Pending'},{id:'middle',status:'Approved'},{id:'next',status:'Pending Approval'}]);
assert.deepEqual(ordered.map(r=>r.id),['new','next','old','middle']);
Object.assign(app.state,{role:'admin',purchaseData:{requests:[request],orders:[],receipts:[]},data:{PRODUCTS:[],SUPPLIERS:[]}});
const rowActions=app.purchaseRequestActions(request);
assert.equal(rowActions.length,1);
assert.equal(text(rowActions[0]),'View');
rowActions[0].props.onClick();
const detail=app.purchaseRequestDetails();
for(const label of ['Edit','Approve','Reject'])assert(nodes(detail).some(n=>n.type==='button'&&text(n)===label),label);
nodes(detail).find(n=>n.type==='button'&&text(n)==='Edit').props.onClick();
assert.equal(app.state.purchaseRequestDetail,null);
assert.equal(app.state.purchaseReviewMode,'edit');
app.state.role='manager';
assert.equal(app.purchaseRequestActions(request).length,1);
assert(!nodes(app.purchaseRequestDetails()).some(n=>n.type==='button'&&['Edit','Approve','Reject'].includes(text(n))));
const orders=app.buildPurchaseOrderWorkspace();
assert(nodes(orders).some(n=>n.type==='button'&&text(n)==='View'));
for(const label of ['View Purchase Order','Create Purchase Request','Stock Receiving','Supplier Balances'])assert(!nodes(orders).some(n=>n.type==='button'&&text(n)===label));
console.log('Purchase request rows show View only; permitted review actions appear in details.');
